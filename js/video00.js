// Video Mode 00 (Bank #255):
// Set Video Bank and Video Pointer to the base of this block:
// $00 - Video mode. Set to 0 for video mode 0.
// $A0-$AF: keyboard buffer. If there are too many keys, it drops keys.
// $F0: Columns (22 for video mode 0)
// $F1: Rows (23 for video mode 0)
// $F2: Charset width (8 for video mode 0)
// $F3: Charset Height (8 for video mode 0)
// $F4-F7: Jiffy timer! Video hardware clock. Will be updated every batch with the current time in miliseconds.
// $F8: Default character color
// $F9: Default cursor color
// $FA: Cursor blink state. 00 = not blinking. 1 = invert fg/bg at cursor.
// $FB - how many keys are in the keyboard buffer.
// $FC: cursor column (it's x)
// $FD: cursor row (it's y)
// $FE: keyboard status: bit 1 = SHIFT, 2 = CTRL, 3 = ALT, 5 = Insert Mode, 6 = Windows(WIN)/Option(MAC)/Meta(ETC), 7 = your suggestion?
// $FF: Color mode (00=COLORDORE (default), 01=CGA_5153)
// $0100-$02F9 (506 bytes): Character map (ASCII codes)
// $0300-$04F9 (506 bytes): Color map (high nibble=bg, low nibble=fg)
// $0500-$0CFF (2KB):       Character ROM (256 × 8 bytes)

