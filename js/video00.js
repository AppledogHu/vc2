// In video00.js
let canvas, ctx, imageData;
let lastFrameTime = 0;
const FRAME_INTERVAL = 1000 / 60; // 60 Hz

function vm0_init_video(canvasId) {
    canvas = document.getElementById(canvasId);
    canvas.width = 176;  // 22 × 8
    canvas.height = 184; // 23 × 8
    ctx = canvas.getContext('2d');
    imageData = ctx.createImageData(176, 184);

    // Scale to fit window
    resize_canvas();
    window.addEventListener('resize', resize_canvas);
}

function resize_canvas() {
    const windowWidth = window.innerWidth;
    const windowHeight = window.innerHeight;
    const aspectRatio = 176 / 184;

    let scale;
    if (windowWidth / windowHeight > aspectRatio) {
        // Window wider than canvas - fit to height
        scale = windowHeight / 184;
    } else {
        // Window taller than canvas - fit to width
        scale = windowWidth / 176;
    }

    canvas.style.width = (176 * scale) + 'px';
    canvas.style.height = (184 * scale) + 'px';
    canvas.style.imageRendering = 'pixelated';
}

function render_video00() {
    const now = performance.now();
    if (now - lastFrameTime < FRAME_INTERVAL) return;
    lastFrameTime = now;

    // Read color mode
    const colorMode = memory[VB][VP + COLORMODE];
    const palette = colorMode === 0 ? COLORDORE : CGA_5153;

    // Read dimensions from video memory
    const MAXCOLS = memory[VB][VP + TCOLS];  // Should be 22
    const MAXROWS = memory[VB][VP + TROWS];  // Should be 23
    const charW = memory[VB][VP + CHARW]; // Should be 8
    const charH = memory[VB][VP + CHARH]; // Should be 8

    const pixels = imageData.data;

    // Render characters
    for (let row = 0; row < MAXROWS; row++) {
        for (let col = 0; col < MAXCOLS; col++) {
            const charIndex = (row * MAXCOLS) + col;
            const charCode = memory[VB][VP + CHARMAP + charIndex];  // ← Missing CHARMAP offset
            const colorByte = memory[VB][VP + COLORMAP + charIndex];

            const bgColor = (colorByte >> 4) & 0x0F;
            const fgColor = colorByte & 0x0F;

            // Get character bitmap
            const charRomBase = VP + CHARSET + (charCode * 8);

            // Draw 8×8 pixels
            for (let py = 0; py < charH; py++) {
                const bitmap = memory[VB][charRomBase + py];
                for (let px = 0; px < charW; px++) {
                    const bit = (bitmap >> (7 - px)) & 1;
                    const color = bit ? palette[fgColor] : palette[bgColor];

                    const screenX = col * charW + px;
                    const screenY = row * charH + py;
                    const pixelIndex = (screenY * 176 + screenX) * 4;

                    pixels[pixelIndex + 0] = (color >> 16) & 0xFF;
                    pixels[pixelIndex + 1] = (color >> 8) & 0xFF;
                    pixels[pixelIndex + 2] = color & 0xFF;
                    pixels[pixelIndex + 3] = 255;
                }
            }
        }
    }

    ctx.putImageData(imageData, 0, 0);
}

