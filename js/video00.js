function vm0_init_bank(bank) {
    // Load PETSCII font at $0500
    //console.log(VP+CHARSET);
    //for (let i = 0; i < PETSCII_FONT.length; i++) {
    //    memory[bank][VP + CHARSET + i] = PETSCII_FONT[i];
    //}

    // Zero page zero.
    for (let i = 0; i < 256; i++) {
        memory[bank][VP + i] = 0x00;
    }
    console.log("Init video: VP=" + VP);

    // Clear character map (506 bytes) - fill with space (0x20)
    for (let i = 0; i < 506; i++) {
        memory[bank][VP + CHARMAP + i] = 0x20;
    }

    // Set default colors (506 bytes) - 0xB5 = bg:11, fg:5
    for (let i = 0; i < 506; i++) {
        memory[bank][VP + COLORMAP + i] = 0xB5;
    }

    // Set video mode and parameters
    memory[bank][VP + VIDEOMODE] = 0x01;
    memory[bank][VP + TCOLS] = 22;
    memory[bank][VP + TROWS] = 23;
    memory[bank][VP + CHARW] = 8;
    memory[bank][VP + CHARH] = 8;
    memory[bank][VP + COLORMODE] = 0x00;

    if (false) {
        // Write "SD-System 64" centered on first row
        let message = "*** SD-System 64 ***";
        let startCol = Math.floor((22 - message.length) / 2);
        for (let i = 0; i < message.length; i++) {
            memory[bank][VP + CHARMAP + startCol + i] = message.charCodeAt(i);
        }

        // Write "ROM/OS V2.0" on second row (row 1 = offset 22)
        message = "ROM/OS V2.0";
        startCol = 0;
        for (let k = 0; k < message.length; k++) {
            memory[bank][VP + CHARMAP + 44 + startCol + k] = message.charCodeAt(k);
        }

        // Write "57,344 BYTES FREE" on third row (row 2 = offset 44)
        message = "57,344 BYTES FREE";
        startCol = 0;
        for (let k = 0; k < message.length; k++) {
            memory[bank][VP + CHARMAP + 66 + startCol + k] = message.charCodeAt(k);
        }
    }
}

// Keyboard buffer management
let keyboardFlags = 0;
document.body.addEventListener('keydown', function(event) {
    // Prevent default for most keys to avoid browser shortcuts
    if (event.key.length === 1 || ['Enter', 'Backspace', 'Tab', 'Escape'].includes(event.key)) {
        event.preventDefault();
    }

    // Update modifier flags
    keyboardFlags = 0;
    if (event.shiftKey) keyboardFlags |= 0x10;
    if (event.ctrlKey)  keyboardFlags |= 0x20;
    if (event.altKey)   keyboardFlags |= 0x40;
    if (event.metaKey)  keyboardFlags |= 0x80;
    memory[VB][VP + KBFLAGS] = keyboardFlags;

    let ascii = 0;

    if (event.key.length === 1) {
        ascii = event.key.charCodeAt(0);
    } else {
        switch(event.key) {
            case 'Enter':      ascii = 13; break;
            case 'Backspace':  ascii = 8; break;
            case 'Tab':        ascii = 9; break;
            case 'Escape':     ascii = 27; break;
            case 'Delete':     ascii = 127; break;

            // Arrow keys - no Ctrl modifier needed!
            case 'ArrowLeft':  ascii = 128; break;
            case 'ArrowDown':  ascii = 129; break;
            case 'ArrowUp':    ascii = 130; break;
            case 'ArrowRight': ascii = 131; break;

            default: ascii = 0; break;
        }
    }

    if (ascii !== 0) {
        if (event.shiftKey) {
            // Shift pressed - convert to lowercase if it's a letter
            if (ascii >= 65 && ascii <= 90) {  // A-Z
                ascii = ascii + 32;  // Convert to a-z
            }
        } else {
            // No shift, default to uppercase
            if (ascii >= 97 && ascii <= 122) {  // a-z
                ascii = ascii - 32;  // Convert to A-Z
            }

        }
        add_to_keyboard_buffer(ascii, keyboardFlags);
    }
});

